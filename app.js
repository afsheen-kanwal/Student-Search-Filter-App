const searchInput = document.querySelector("#searchInput")
const ageFilter = document.querySelector("#ageFilter")
const container = document.querySelector(".container")
const students = Object.values(studentsIfo)

function showStudents(list) {
    container.innerHTML = "";
    document.getElementById("count").textContent = list.length;

    if (list.length === 0) {
        container.innerHTML = `<p class="no-result">No student found 😔</p>`;
        return;
    }

    list.forEach((student, index) => {
        container.innerHTML += `
          <div class="card" style="animation-delay: ${index * 0.08}s">
            <img src="${student.Image}" alt="${student.studentname}">
            <h3>Student Name <br> ${student.studentname}</h3>
            <p>Student Age : ${student.studentage}</p>
            <p>Roll Number : ${student.rollnumber}</p>
          </div>
        `;
    });
}
function applyFilters() {
    const text = searchInput.value.toLowerCase().trim();
    const ageRange = ageFilter.value;

    const result = students.filter((student) => {
        const age = Number(student.studentage);

        const nameMatch = student.studentname.toLowerCase().includes(text);

        let ageMatch = true;
        if (ageRange === "20-22") ageMatch = age >= 20 && age <= 22;
        else if (ageRange === "23-25") ageMatch = age >= 23 && age <= 25;
        else if (ageRange === "26-30") ageMatch = age >= 26;

        return nameMatch && ageMatch;
    });

    showStudents(result);
}



searchInput.addEventListener("input", applyFilters);
ageFilter.addEventListener("change", applyFilters);

showStudents(students); 